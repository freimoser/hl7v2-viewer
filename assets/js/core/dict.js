export function fieldInfo(segId, n) {
  const seg = SEGMENTS[segId];
  const f = seg?.fields?.[n];
  if (!f) return { name: segId === "" ? "" : `Feld ${n}`, type: "", desc: "", known: false, key: false };
  return { name: f[0], type: f[1], desc: f[2], codes: f[3]?.codes, key: !!f[3]?.key, known: true };
}
export function segmentInfo(id) {
  if (SEGMENTS[id]) return { name: SEGMENTS[id].name, desc: SEGMENTS[id].desc, known: true, local: false };
  if (/^Z[A-Z0-9]{2}$/.test(id)) return { name: "Z-Segment (lokale Erweiterung)", desc: "Z-Segmente sind frei vereinbarte Erweiterungen einzelner Systeme. Ihr Inhalt steht in keiner HL7-Tabelle; er ergibt sich nur aus der Schnittstellenbeschreibung des Absenders.", known: false, local: true };
  return { name: id, desc: "Dieses Segment ist im Viewer nicht beschrieben. Felder werden als „Feld n“ angezeigt.", known: false, local: false };
}
export function componentName(type, k) {
  return COMPONENTS[type]?.[k - 1] || `Komponente ${k}`;
}
export function codeMeaning(segId, n, value) {
  const c = fieldInfo(segId, n).codes;
  return c && value in c ? c[value] : "";
}
